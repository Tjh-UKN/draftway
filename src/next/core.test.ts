import {describe, expect, it} from 'vitest';
import {addSurface, advanceDemoRuns, applyRunMapChange, cancelDemoRun, closeSessionTab, closeSurface, createMapNode, createSession, initialWorkbench, mergePanes, moveSurface, openSession, parseWorkbench, placeArtifact, renameMapNode, resumeDemoRun, reorderSessionTab, selectWorkspaceTab, sessionNodeIds, splitSurface, startDemoRun, updateWorkspace} from './core';
import {sessionAdapter} from './adapters';
import {seedState} from './model';

describe('workspace shell records and lifecycle', () => {
  it('migrates the design data without changing node IDs, progress or notes', () => {
    const old = seedState();
    old.spaces[0].notes = 'My existing notes';
    const before = JSON.stringify(old);
    const next = initialWorkbench(old);
    expect(JSON.stringify(old)).toBe(before);
    expect(next.spaces[0].nodes).toEqual(old.spaces[0].nodes);
    expect(next.spaces[0].surfaces.find(s => s.integrationId === 'note')?.text).toBe('My existing notes');
    expect(parseWorkbench(JSON.parse(JSON.stringify(next)))).toEqual(next);
  });
  it('keeps execution alive after closing a tab and routes a notification back to the original session', () => {
    let state = createSession(initialWorkbench(), 'design', 'link', 'session-1', 0);
    state = startDemoRun(state, 'session-1', 'Test', 'succeeded', 'run-1', 100);
    const nodeBefore = structuredClone(state.spaces[0].nodes);
    state = closeSessionTab(state, 'design', 'session-1');
    state = {...state, activeId: 'review'};
    state = advanceDemoRuns(state, 7200);
    expect(state.activeId).toBe('review');
    expect(state.sessions[0].messages).toHaveLength(2);
    expect(state.notices[0]).toMatchObject({workspaceId: 'design', sessionId: 'session-1', read: false});
    expect(state.spaces[0].nodes).toEqual(nodeBefore);
    expect(advanceDemoRuns(state, 10000)).toBe(state);
    state = openSession(state, state.notices[0].sessionId!);
    expect(state.activeId).toBe('design');
    expect(state.spaces[0].sessionTabs.activeId).toBe('session-1');
    expect(state.notices[0].read).toBe(true);
    expect(state.spaces[0].surfaces.filter(s => s.resourceId === 'session-1')).toHaveLength(0);
    expect(parseWorkbench(JSON.parse(JSON.stringify(state)))).toEqual(state);
  });
  it('preserves every concurrent result; reading one session does not clear another', () => {
    let state = createSession(initialWorkbench(), 'design', 'link', 'one', 0);
    state = createSession(state, 'design', 'link', 'two', 0);
    state = startDemoRun(state, 'one', 'One', 'succeeded', 'r1', 0);
    state = startDemoRun(state, 'two', 'Two', 'failed', 'r2', 0);
    state = advanceDemoRuns(state, 7001);
    expect(state.notices).toHaveLength(2);
    expect(state.artifacts).toHaveLength(1);
    state = openSession(state, 'one');
    expect(state.sessions.find(s => s.id === 'two')?.unread).toBe(true);
    expect(state.notices.find(n => n.sessionId === 'two')?.read).toBe(false);
    expect(state.runs.map(r => r.state)).toEqual(['succeeded', 'failed']);
  });
  it('does not accept a second running turn, and resumes needs-input exactly once', () => {
    let state = createSession(initialWorkbench(), 'design', 'link', 'one', 0);
    state = startDemoRun(state, 'one', 'First', 'needs_input', 'r1', 0);
    expect(startDemoRun(state, 'one', 'Duplicate', 'succeeded', 'r2', 0)).toBe(state);
    state = advanceDemoRuns(state, 7001);
    expect(state.runs[0].state).toBe('needs_input');
    expect(startDemoRun(state, 'one', 'While waiting', 'succeeded', 'r3', 0)).toBe(state);
    expect(state.artifacts).toHaveLength(0);
    state = resumeDemoRun(state, 'r1', 8000);
    expect(state.notices[0].read).toBe(true);
    expect(state.sessions[0].unread).toBe(false);
    state = advanceDemoRuns(state, 12001);
    expect(state.runs[0].state).toBe('succeeded');
    expect(state.notices).toHaveLength(1);
    expect(state.artifacts).toHaveLength(1);
    expect(state.sessions[0].messages).toHaveLength(3);
    expect(advanceDemoRuns(state, 13000)).toBe(state);
  });
  it('does not finish a cancelled run on reload and keeps drafts', () => {
    let state = createSession(initialWorkbench(), 'design', null, 'one', 0);
    state = startDemoRun(state, 'one', 'Test', 'succeeded', 'r1', 0);
    state.sessions[0].draft = 'Next message';
    state = cancelDemoRun(state, 'r1');
    const restored = parseWorkbench(JSON.parse(JSON.stringify(state)));
    expect(advanceDemoRuns(restored, 20000)).toBe(restored);
    expect(restored.notices).toHaveLength(0);
    expect(restored.sessions[0].draft).toBe('Next message');
  });
  it('restores split ratio, active tabs, node selection and camera, preserving closed note content', () => {
    let state = initialWorkbench();
    state = updateWorkspace(state, 'design', space => {
      let next = splitSurface(space, 'design-view-2');
      next = {...next, graph: {selectedId: 'link', focusId: null, collapsed: ['think'], camera: {x: 42, y: -17, zoom: .9}}, layout: {...next.layout, ratio: .65}};
      return next;
    });
    let restored = parseWorkbench(JSON.parse(JSON.stringify(state)));
    expect(restored.spaces[0].layout.ratio).toBe(.65);
    expect(restored.spaces[0].graph.camera).toEqual({x: 42, y: -17, zoom: .9});
    const note = restored.spaces[0].surfaces.find(s => s.integrationId === 'note')!;
    restored = updateWorkspace(restored, 'design', space => closeSurface(space, note.id));
    expect(restored.spaces[0].surfaces.find(s => s.id === note.id)?.text).toBe(note.text);
    restored = updateWorkspace(restored, 'design', space => addSurface(space, note));
    expect(restored.spaces[0].surfaces.filter(s => s.id === note.id)).toHaveLength(1);
    expect(parseWorkbench(JSON.parse(JSON.stringify(restored)))).toEqual(restored);
  });
  it('reorders and moves tabs between groups with exactly one owner', () => {
    const base = initialWorkbench().spaces[0];
    let space = splitSurface(base, 'design-view-2');
    space = moveSurface(space, 'design-view-1', 'secondary', 'design-view-2');
    expect(space.layout.panes[1].tabs).toEqual(['design-view-1', 'design-view-2']);
    expect(space.layout.panes.flatMap(p => p.tabs).filter(id => id === 'design-view-1')).toHaveLength(1);
    space = moveSurface(space, 'design-view-0', 'secondary');
    expect(space.layout.panes).toHaveLength(1);
    expect(space.layout.activePaneId).toBe('secondary');
    expect(mergePanes(space).layout.panes[0].tabs).toEqual(['design-view-1', 'design-view-2', 'design-view-0']);
  });
  it('rejects orphaned and multiply-owned references but preserves unavailable integrations', () => {
    const state = initialWorkbench();
    state.spaces[0] = addSurface(state.spaces[0], {id: 'future', integrationId: 'future.adapter', title: 'Future view', text: 'Keep me'});
    expect(parseWorkbench(JSON.parse(JSON.stringify(state))).spaces[0].surfaces.at(-1)?.text).toBe('Keep me');
    const duplicate = structuredClone(state);
    duplicate.spaces[0].layout.panes[0].tabs.push('future');
    expect(() => parseWorkbench(duplicate)).toThrow();
    const orphan = structuredClone(state);
    orphan.spaces[0].layout.panes[0].tabs.push('missing');
    expect(() => parseWorkbench(orphan)).toThrow();
    const badCamera = structuredClone(state);
    badCamera.spaces[0].graph.camera = {x: 0, y: 0, zoom: 0};
    expect(() => parseWorkbench(badCamera)).toThrow();
    expect(sessionAdapter('demo-agent')).toBeDefined();
    expect(sessionAdapter('codex')).toBeUndefined();
  });
  it('never completes a different provider with the simulator and marks focused session tabs read', () => {
    let state = createSession(initialWorkbench(), 'design', 'link', 'one', 0);
    state = startDemoRun(state, 'one', 'Test', 'succeeded', 'r1', 0);
    const future = structuredClone(state);
    future.sessions[0].integrationId = 'future-provider';
    expect(advanceDemoRuns(future, 10000)).toBe(future);
    state = advanceDemoRuns(state, 10000);
    expect(state.sessions[0].unread).toBe(true);
    state = openSession(state, 'one');
    expect(state.sessions[0].unread).toBe(false);
    expect(state.notices[0].read).toBe(true);
  });
  it('creates provider-specific workspace conversations without producing nodes or tabs', () => {
    let state = initialWorkbench();
    const nodes = structuredClone(state.spaces[0].nodes);
    const layout = structuredClone(state.spaces[0].layout);
    for (const provider of ['codex', 'claude', 'pi'] as const) state = createSession(state, 'design', null, provider, 10, provider);
    expect(state.sessions.map(s => s.agentId)).toEqual(['codex', 'claude', 'pi']);
    expect(state.sessions.every(s => s.workspaceId === 'design' && s.nodeId === null)).toBe(true);
    expect(state.spaces[0].nodes).toEqual(nodes);
    expect(state.spaces[0].layout).toEqual(layout);
    expect(state.spaces[0].sessionTabs.activeId).toBe('pi');
  });
  it('restores each workspace tab order, active conversation and drafts independently', () => {
    let state = createSession(initialWorkbench(), 'design', null, 'one', 10);
    state = createSession(state, 'design', null, 'three', 11, 'claude');
    state = updateWorkspace(state, 'design', w => reorderSessionTab(w, 'three', 'one'));
    state.sessions[0].draft = 'Retained draft';
    state = createSession(state, 'review', null, 'two', 12, 'pi');
    const restored = parseWorkbench(JSON.parse(JSON.stringify(state)));
    expect(restored.spaces[0].sessionTabs.ids).toEqual(['three', 'one']);
    expect(restored.spaces[0].sessionTabs.activeId).toBe('three');
    expect(restored.spaces[1].sessionTabs.activeId).toBe('two');
    expect(restored.sessions[0].draft).toBe('Retained draft');
    const closed = closeSessionTab(restored, 'review', 'two');
    expect(closed.sessions).toHaveLength(3);
    expect(closed.spaces[0].sessionTabs.activeId).toBe('three');
    expect(closed.spaces[1].sessionTabs.activeId).toBe('workspace');
  });
  it('creates result nodes only for an explicit map action or a manually retained result', () => {
    let state = createSession(initialWorkbench(), 'design', null, 'one', 0);
    const before = state.spaces[0].nodes.length;
    state = startDemoRun(state, 'one', 'Reply only', 'succeeded', 'r1', 0);
    state = advanceDemoRuns(state, 7001);
    expect(state.spaces[0].nodes).toHaveLength(before);
    state = placeArtifact(state, 'r1-artifact', 8000);
    expect(state.spaces[0].nodes).toHaveLength(before + 1);
    state = placeArtifact(state, 'r1-artifact', 9000);
    expect(state.spaces[0].nodes).toHaveLength(before + 1);
    state = startDemoRun(state, 'one', 'Retain result', 'succeeded', 'r2', 10000, 'artifact');
    state = advanceDemoRuns(state, 17001);
    expect(state.spaces[0].nodes).toHaveLength(before + 2);
    expect(state.spaces[0].nodes.at(-1)?.updates?.[0].sessionId).toBe('one');
    expect(sessionNodeIds(state.sessions[0])).toContain('artifact-r2-artifact');
    expect(parseWorkbench(JSON.parse(JSON.stringify(state)))).toEqual(state);
  });
  it('applies content and progress changes once, with source-session history and unchanged task progress', () => {
    let state = createSession(initialWorkbench(), 'design', 'link', 'one', 0);
    const before = state.spaces[0].nodes.find(n => n.id === 'link')!;
    state = startDemoRun(state, 'one', 'Record progress', 'succeeded', 'r1', 0, 'progress', 'link');
    state = advanceDemoRuns(state, 7001);
    let node = state.spaces[0].nodes.find(n => n.id === 'link')!;
    expect(node.body).toBe(before.body);
    expect(node.progress).toBe(before.progress);
    expect(node.updates).toHaveLength(1);
    state = applyRunMapChange(state, 'r1', 8000);
    expect(state.spaces[0].nodes.find(n => n.id === 'link')?.updates).toHaveLength(1);
    state = startDemoRun(state, 'one', 'Update content', 'succeeded', 'r2', 9000, 'update', 'link');
    state = advanceDemoRuns(state, 16001);
    node = state.spaces[0].nodes.find(n => n.id === 'link')!;
    expect(node.body).toContain('模拟更新');
    expect(node.progress).toBe(before.progress);
    expect(node.updates?.every(u => u.sessionId === 'one')).toBe(true);
    expect(node.updates).toHaveLength(2);
  });
  it('rejects cross-workspace map writes and does not modify maps for failed runs', () => {
    let state = createSession(initialWorkbench(), 'design', 'link', 'one', 0);
    expect(startDemoRun(state, 'one', 'Cross workspace', 'succeeded', 'bad', 0, 'update', 'review-root')).toBe(state);
    const before = structuredClone(state.spaces[0].nodes);
    state = startDemoRun(state, 'one', 'Fail', 'failed', 'r1', 0, 'artifact');
    state = advanceDemoRuns(state, 7001);
    expect(state.spaces[0].nodes).toEqual(before);
    expect(sessionNodeIds({...state.sessions[0], linkedNodeIds: ['link', 'spaces']})).toEqual(['link', 'spaces']);
  });
  it('migrates old session-tab snapshots without losing conversations or rewriting the source', () => {
    const raw = JSON.parse(JSON.stringify(createSession(initialWorkbench(), 'design', null, 'one', 0)));
    raw.version = 1;
    delete raw.spaces[0].sessionWindow;
    delete raw.spaces[0].sessionTabs;
    delete raw.spaces[0].sessionPanelOpen;
    raw.spaces[0].surfaces.push({id: 'old-session-tab', integrationId: 'session', title: 'Old', resourceId: 'one'});
    raw.spaces[0].layout.panes[0].tabs.push('old-session-tab');
    raw.spaces[0].layout.panes[0].activeId = 'old-session-tab';
    const serialized = JSON.stringify(raw);
    const restored = parseWorkbench(raw);
    expect(JSON.stringify(raw)).toBe(serialized);
    expect(restored.version).toBe(2);
    expect(restored.spaces[0].sessionTabs.activeId).toBe('one');
    expect(restored.sessions).toHaveLength(1);
  });
  it('persists document, code and artifact contents and rejects malformed update records', () => {
    const state = initialWorkbench();
    for (const kind of ['document', 'code', 'artifact'] as const) state.spaces[0].nodes.push({id: `new-${kind}`, parentId: 'northstar', side: 1, kind, title: kind, body: 'Saved content', progress: 0, due: '', ...{steps: [], reference: 'kv_trace/', completed: true}, updates: [{id: `u-${kind}`, text: 'Manual update', at: 1}]});
    const restored = parseWorkbench(JSON.parse(JSON.stringify(state)));
    expect(restored.spaces[0].nodes.slice(-3).map(n => n.kind)).toEqual(['document', 'code', 'artifact']);
    expect(restored.spaces[0].nodes.at(-1)).toMatchObject({task:true,progress:100,body:'Saved content\n\n引用：kv_trace/'});
    expect(restored.spaces[0].nodes.at(-1)).not.toHaveProperty('reference');
    restored.spaces[0].nodes.at(-1)!.updates![0].at = Number.NaN;
    expect(() => parseWorkbench(restored)).toThrow();
  });
  it('returns to the last used tab when closing, retaining the running conversation for reopening', () => {
    let state = createSession(initialWorkbench(), 'design', null, 'one', 0);
    state = createSession(state, 'design', null, 'two', 0);
    state = openSession(state, 'one');
    state = startDemoRun(state, 'one', 'Name from first prompt', 'succeeded', 'r1', 0);
    state = closeSessionTab(state, 'design', 'one');
    expect(state.spaces[0].sessionTabs.activeId).toBe('two');
    expect(state.runs[0].state).toBe('running');
    expect(state.sessions[0].title).toBe('Name from first prompt');
    state = selectWorkspaceTab(state, 'design');
    state = advanceDemoRuns(state, 7001);
    expect(state.spaces[0].sessionTabs.activeId).toBe('workspace');
    expect(state.sessions[0].unread).toBe(true);
    state = openSession(state, 'one');
    state = openSession(state, 'one');
    expect(state.spaces[0].sessionTabs.ids.filter(id => id === 'one')).toHaveLength(1);
    expect(state.notices[0].read).toBe(true);
  });
  it('rejects duplicate, missing and cross-workspace session tabs', () => {
    const state = createSession(initialWorkbench(), 'design', null, 'one', 0);
    const duplicate = structuredClone(state); duplicate.spaces[0].sessionTabs.ids.push('one');
    expect(() => parseWorkbench(duplicate)).toThrow();
    const missing = structuredClone(state); missing.spaces[0].sessionTabs.activeId = 'missing';
    expect(() => parseWorkbench(missing)).toThrow();
    const foreign = structuredClone(state); foreign.spaces[1].sessionTabs.ids.push('one');
    expect(() => parseWorkbench(foreign)).toThrow();
  });

  it('adds a node directly under the clicked parent with no content or placement form', () => {
    const state = initialWorkbench();
    const next = createMapNode(state, 'design', 'act', 'direct-node');
    expect(next.spaces[0].nodes.at(-1)).toMatchObject({id: 'direct-node', parentId: 'act', title: '新节点', body: '', kind: 'idea'});
    expect(next.spaces[0].graph.selectedId).toBe('direct-node');
    expect(next.sessions).toHaveLength(0);
    expect(state.spaces[0].nodes.some(n => n.id === 'direct-node')).toBe(false);
    expect(createMapNode(next, 'design', 'missing', 'bad')).toBe(next);
    expect(createMapNode(next, 'review', 'act', 'cross')).toBe(next);
  });
  it('renames a node while preserving its latest body and associations', () => {
    const state = createSession(initialWorkbench(), 'design', 'act', 'inline-session', 0);
    state.spaces[0].nodes.find(n => n.id === 'act')!.body = 'Latest AI update';
    const next = renameMapNode(state, 'design', 'act', '直接修改节点');
    expect(next.spaces[0].nodes.find(n => n.id === 'act')).toEqual({...state.spaces[0].nodes.find(n => n.id === 'act'), title: '直接修改节点'});
    expect(next.sessions).toEqual(state.sessions);
    expect(renameMapNode(next, 'design', 'act', '   ')).toBe(next);
    expect(renameMapNode(next, 'review', 'act', 'Foreign workspace')).toBe(next);
    const unicode = renameMapNode(next, 'design', 'act', 'a' + '🚀'.repeat(100));
    expect(() => parseWorkbench(JSON.parse(JSON.stringify(unicode)))).not.toThrow();
    expect(unicode.spaces[0].nodes.find(n => n.id === 'act')!.title.length).toBeLessThanOrEqual(120);
  });

});
